// Copies contracts/abi/Earmark.json into src/abi.ts as a const-typed export.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, '../../contracts/abi/Earmark.json');
const out = resolve(here, '../src/abi.ts');

if (!existsSync(src)) {
  console.error(`sync-abi: ${src} not found. Build the contracts first (contracts session publishes abi/Earmark.json).`);
  process.exit(1);
}
const json = JSON.parse(readFileSync(src, 'utf8'));
const abi = Array.isArray(json) ? json : json.abi;
if (!Array.isArray(abi)) {
  console.error('sync-abi: no "abi" array in Earmark.json');
  process.exit(1);
}
const body = `// Generated by \`npm run sync-abi\` from contracts/abi/Earmark.json. Do not edit by hand.\nexport const earmarkAbi = ${JSON.stringify(abi, null, 2)} as const;\n`;
writeFileSync(out, body);
console.log(`sync-abi: wrote ${abi.length} entries to src/abi.ts`);
