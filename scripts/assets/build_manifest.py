#!/usr/bin/env python3
"""Rebuild earmark-app/public/media/manifest.json by scanning the media folder.

Usage: python3 -I scripts/assets/build_manifest.py
"""
import glob
import json
import os
import re
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
MEDIA = os.path.join(ROOT, 'earmark-app/public/media')
HARTWELL = os.path.join(ROOT, 'hartwell-supply/frontend/public/media')

KIND = {
    'story-maya-couch': ('still', '3:2'), 'story-alex-driveway': ('still', '3:2'),
    'story-alex-shoveling': ('still', '3:2'), 'hartwell-storefront': ('still', '16:9'),
}


def main():
    images = {}
    for p in sorted(glob.glob(os.path.join(MEDIA, '*-*.webp'))):
        m = re.match(r'(.+)-(\d+)\.webp$', os.path.basename(p))
        if not m:
            continue
        name, w = m.group(1), int(m.group(2))
        with Image.open(p) as im:
            width, height, alpha = im.width, im.height, im.mode == 'RGBA'
        e = images.setdefault(name, {'kind': KIND.get(name, ('product-cutout', '1:1'))[0],
                                     'aspect': KIND.get(name, ('', '1:1'))[1], 'alpha': alpha, 'files': []})
        e['files'].append({'src': f'/media/{name}-{w}.webp', 'width': width, 'height': height})
    for name, e in images.items():
        e['files'].sort(key=lambda f: f['width'])
        e['width'], e['height'] = e['files'][-1]['width'], e['files'][-1]['height']
        e['srcset'] = ', '.join(f"{f['src']} {f['width']}w" for f in e['files'])
        e['alsoInHartwell'] = os.path.exists(os.path.join(HARTWELL, f'{name}-640.webp'))

    manifest = {'generated': 'scripts/assets/build_manifest.py', 'images': images}

    frames = sorted(glob.glob(os.path.join(MEDIA, 'hero/frames/f*.webp')))
    if frames:
        with Image.open(frames[0]) as im:
            fw, fh = im.size
        manifest['hero'] = {
            'frames': {'pattern': '/media/hero/frames/f{0000}.webp', 'first': '/media/hero/frames/f0001.webp',
                       'count': len(frames), 'fps': 15, 'width': fw, 'height': fh, 'pad': 4, 'start': 1},
            'video': {'src': '/media/hero/hero.mp4', 'width': fw, 'height': fh, 'duration': 10.04, 'audio': False},
            'poster': {'src': '/media/hero/poster.webp', 'width': fw, 'height': fh},
        }

    call_json = os.path.join(MEDIA, 'call/call.json')
    if os.path.exists(call_json):
        with open(call_json) as f:
            c = json.load(f)
        manifest['call'] = {'audio': '/media/call/call.mp3', 'transcript': '/media/call/call.json', 'duration': c.get('duration')}
    else:
        manifest['call'] = {'audio': '/media/call/call.mp3', 'transcript': '/media/call/call.json', 'pending': True,
                            'note': 'Generated by scripts/assets/make-call-audio.mjs once ELEVENLABS_API_KEY is set.'}

    with open(os.path.join(MEDIA, 'manifest.json'), 'w') as f:
        json.dump(manifest, f, indent=2)
    print('images:', len(images), '| hero frames:', len(frames), '| call:', 'ready' if 'duration' in manifest['call'] else 'pending')


if __name__ == '__main__':
    main()
